import { describe, expect, it } from "vitest";
import {
  idSchema,
  paginationSchema,
  updatedAtSchema,
} from "@/shared/validation/params";

// Message from docs/plataforma/mensagens-de-validacao.md.
const PAGINATION = "Informe um número inteiro a partir de 1.";

describe("idSchema", () => {
  it("accepts a UUID generated by the database", () => {
    const id = "3f2b8c1e-9d4a-4f6b-8e2c-1a7d5b9c0e3f";
    expect(idSchema.parse(id)).toBe(id);
  });

  it("accepts an id of seed-demo.sql, made by md5(...)::uuid", () => {
    // md5('glow-demo:category:Lavagem')::uuid: neither the version digit (c)
    // nor the variant digit (7) follows RFC 9562.
    const id = "4e31423b-fe30-cf42-7e5a-eebc618ac6e6";
    expect(idSchema.parse(id)).toBe(id);
  });

  it("rejects 123 and not-a-uuid", () => {
    expect(idSchema.safeParse("123").success).toBe(false);
    expect(idSchema.safeParse("not-a-uuid").success).toBe(false);
  });
});

describe("paginationSchema", () => {
  const DEFAULT_PAGE_SIZE = 20;
  const schema = paginationSchema(DEFAULT_PAGE_SIZE);

  function messageOf(value: unknown): string | undefined {
    const result = schema.safeParse(value);
    return result.success ? undefined : result.error.issues[0]?.message;
  }

  it("uses page 1 and the given page size when they are missing", () => {
    expect(schema.parse({})).toEqual({ page: 1, pageSize: DEFAULT_PAGE_SIZE });
  });

  it("converts query string values", () => {
    expect(schema.parse({ page: "2", pageSize: "10" })).toEqual({
      page: 2,
      pageSize: 10,
    });
  });

  it("limits pageSize to 50", () => {
    expect(schema.parse({ pageSize: "80" })).toEqual({ page: 1, pageSize: 50 });
  });

  it("rejects page or pageSize 0, -1, 1.5 and abc", () => {
    for (const value of ["0", "-1", "1.5", "abc"]) {
      expect(messageOf({ page: value })).toBe(PAGINATION);
      expect(messageOf({ pageSize: value })).toBe(PAGINATION);
    }
  });

  it("discards unknown parameters", () => {
    expect(schema.parse({ page: "1", orderBy: "password" })).toEqual({
      page: 1,
      pageSize: DEFAULT_PAGE_SIZE,
    });
  });
});

describe("updatedAtSchema", () => {
  // Message of docs/plataforma/mensagens-de-validacao.md (L6 of #37).
  const STALE_VERSION = "Atualize a página e tente novamente.";

  function versionMessageOf(value: unknown): string | undefined {
    const result = updatedAtSchema.safeParse(value);
    return result.success ? undefined : result.error.issues[0]?.message;
  }

  it("accepts the updatedAt as the database sends it", () => {
    const updatedAt = "2026-10-20T13:45:12.345678+00:00";
    expect(updatedAtSchema.parse(updatedAt)).toBe(updatedAt);
  });

  it("rejects an absent or malformed updatedAt", () => {
    for (const value of [undefined, "", "20/10/2026", "abc"]) {
      expect(versionMessageOf(value)).toBe(STALE_VERSION);
    }
  });
});
